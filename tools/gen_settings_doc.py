"""Generate the settings tables of docs/configuration.md and docs/configuration.zh.md from the settings registry.

The registry (`backend/slotserve/services/app_settings.py`, `REGISTRY`) is the single source: every setting with
its group, level, default and description in both languages. This script rewrites only the block between

    <!-- settings:start ... -->
    <!-- settings:end -->

and leaves the hand-written rest of each page alone (compose variables, launch arguments, backups, setup code,
requests from other pages, command line).

    python tools/gen_settings_doc.py            # rewrite the docs
    python tools/gen_settings_doc.py --check    # exit 1 when the docs are out of date (a backend test runs this)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = {"en": ROOT / "docs" / "configuration.md", "zh": ROOT / "docs" / "configuration.zh.md"}
START = "<!-- settings:start (generated by tools/gen_settings_doc.py from the settings registry; do not edit) -->"
END = "<!-- settings:end -->"

TEXT = {
    "en": {
        "head": ("Variable", "Default", "Level", "Description"),
        "empty": "*empty*",
        "tiers": {"basic": "basic", "advanced": "advanced", "expert": "expert"},
        "danger": "⚠️ **Runs as root on the host.** ",
        "intro": (
            "Admins change every setting except the deployment parameters in **Admin → System settings**, without a "
            "restart: overrides live in the database and win over `.env`, and **Use default** removes one. Each "
            "change is in the audit log with its old and new value (secrets only as a fingerprint) and can be "
            "undone. *Level* is where the setting appears: *basic* on the policy cards, *advanced* in the full "
            "list, *expert* folded away. Settings marked ⚠️ can run commands as root on the host (an engine "
            "command, a mounted directory, a forwarder image): changing them is recorded as a sensitive change and "
            "announced to all admins (a later version also asks for your password again). The deployment "
            "parameters are read at start: change them in `.env` and "
            "restart."
        ),
    },
    "zh": {
        "head": ("变量", "默认值", "层级", "说明"),
        "empty": "*空*",
        "tiers": {"basic": "常用", "advanced": "进阶", "expert": "专家"},
        "danger": "⚠️ **以 root 身份在宿主机上执行。** ",
        "intro": (
            "除部署参数外，所有设置都可由管理员在**管理 → 系统设置**中直接修改，无需重启："
            "修改保存在数据库中，优先于 `.env`；点**恢复默认**即可取消覆盖。"
            "每次修改都会以修改前后的值记入审计日志（密钥只记录指纹），并且可以撤销。"
            "*层级*表示设置出现的位置：*常用*在策略卡片上，*进阶*在完整列表中，*专家*默认折叠。"
            "标有 ⚠️ 的设置可以在宿主机上以 root 身份执行命令（推理后端命令、挂载目录、转发镜像）："
            "修改会记为敏感修改并通知所有管理员（之后的版本还会要求再次输入密码）。"
            "部署参数在启动时读取：请在 `.env` 中修改并重启。"
        ),
    },
}


def _registry():
    sys.path.insert(0, str(ROOT / "backend"))
    from slotserve.config import Settings
    from slotserve.services import app_settings

    return Settings, app_settings


def _default(value, empty: str) -> str:
    if value is None or value == "":
        return empty
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if isinstance(value, Path):
        value = value.as_posix()
    return f"`{value}`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(lang: str) -> str:
    settings_cls, app_settings = _registry()
    t = TEXT[lang]
    lines = [START, "", t["intro"], ""]
    for group, *titles in app_settings.GROUPS:
        keys = [k for k, spec in app_settings.REGISTRY.items() if spec.group == group]
        if not keys:
            continue
        lines += [f"### {titles[0] if lang == 'en' else titles[1]}", ""]
        lines += ["| " + " | ".join(t["head"]) + " |", "| --- | --- | --- | --- |"]
        for key in keys:
            spec = app_settings.REGISTRY[key]
            if spec.doc_default is not None:
                default = spec.doc_default[0 if lang == "en" else 1]
            else:
                default = _default(settings_cls.model_fields[key].default, t["empty"])
            desc = spec.doc[0 if lang == "en" else 1]
            if spec.danger:
                desc = t["danger"] + desc
            row = [f"`{app_settings.env_var(key)}`", default, t["tiers"][spec.tier], _cell(desc)]
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def update(text: str, block: str, path: Path) -> str:
    if START not in text or END not in text:
        raise SystemExit(f"{path}: markers {START!r} / {END!r} not found")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check that the docs are up to date")
    args = parser.parse_args(argv)
    stale = []
    for lang, path in DOCS.items():
        text = path.read_text(encoding="utf-8")
        new = update(text, render(lang), path)
        if new != text:
            stale.append(path)
            if not args.check:
                path.write_text(new, encoding="utf-8", newline="\n")
    if args.check and stale:
        names = ", ".join(p.relative_to(ROOT).as_posix() for p in stale)
        print(f"out of date: {names}; run python tools/gen_settings_doc.py", file=sys.stderr)
        return 1
    if not args.check:
        print("updated: " + (", ".join(p.relative_to(ROOT).as_posix() for p in stale) or "nothing"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
